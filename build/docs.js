const { src, dest, series }  = require( 'gulp' ),
      ClosureCompiler        = require('google-closure-compiler').gulp(),
      postProcessor          = require( 'es2-postprocessor' );
      es2ToES3               = require( 'es2-to-es3' ),
      fs                     = require('fs'),
      JSDOM                  = require('jsdom').JSDOM,
      globalVariables        = 'document,navigator,screen,parseFloat,Number',
      { tempDir, copyright } = require('./common.js');

let minify       = false;
let uaObjectName = 'ua';
let formatting   = 'PRETTY_PRINT';
let funcConpare;

function createListFile( category, cb ){
    fs.readFile(
        './src/js/iAm/CONST/Enum' + category + '.js',
        function( error, buffer ){
            if( !error ){
                const obj = eval(
                        '(' +
                            buffer.toString()
                                .split( 'iAm.Enum' + category + ' =' )[ 1 ]
                                .split( 'iAm.DEFINE.MINIFY' ).join( '' + minify )
                                .split( 'iAm.UNKNOWN_VALUE' ).join( minify ? '0' : '""' )
                                .split( '};' ).join( '}' ) +
                        ')'
                    ), list = [], result = [];

                for( var name in obj ){
                    list.push(
                        {
                            displayName : name.split( '$R' ).join( '®' ).split( '$TM' ).join( '™' ).split( '$_' ).join( '-' )
                                              .split( '_' ).join( ' ' ).split( '$VL' ).join( '|' ),
                            value       : obj[ name ]
                        }
                    );
                };
                list.sort(
                    function( a, b ){
                        return a.displayName.toLowerCase() > b.displayName.toLowerCase() ? 1 : -1;
                    }
                );
                while( list.length ){
                    let item = list.shift();
                    result.push( item.value, item.displayName );
                };
                fs.writeFile(
                    './src/js/docs/catalog/' + category + 'ValueToDisplayLabel.js',
                    '// THIS FILE GENERATED BY "gulp dist", DONT EDIT!\n\n' +
                    'goog.provide( "catalog.' + category + 'ValueToDisplayLabel" );\n\n' +
                    'catalog.' + category + 'ValueToDisplayLabel = ' + JSON.stringify( result, null, '    ' ),
                    cb
                );
            };
        }
    );
};

function compile( target ){
    return function(){
        return src(
                [
                    './src/closure-primitives/base.js',
                    './.submodules/es2-json/.submodules/es2-core/src/js/**/*.js',
                    './.submodules/es2-json/src/js/**/*.js',
                    tempDir + '/' + uaObjectName + '.js',
                     './src/js/**/*.js'
                ]
            ).pipe(
                ClosureCompiler(
                    {
                        dependency_mode   : 'PRUNE',
                        entry_point       : 'goog:page.' + target,
                        compilation_level : 'ADVANCED',
                        define            : [
                            'iAm.DEFINE.MINIFY=' + minify,
                            'JSON2.DEFINE.USE_REPLACER=false'
                        ],
                        warning_level     : 'VERBOSE',
                        language_in       : 'ECMASCRIPT3',
                        language_out      : 'ECMASCRIPT3',
                        output_wrapper    :
                            '(function(window, ' + globalVariables + '){\n' +
                                '%output%\n' +
                            '})(this, ' + globalVariables + ');'
                    }
                )
            ).pipe(
                postProcessor.gulp(
                    {
                        hoist : true
                    }
                )
            ).pipe(
                ClosureCompiler(
                    {
                        warning_level : 'QUIET',
                        language_in   : 'ECMASCRIPT3',
                        language_out  : 'ECMASCRIPT3'
                    }
                )
            ).pipe(
                postProcessor.gulp(
                    {
                        minIEVersion    : 5,
                        minOperaVersion : 7,
                        minGeckoVersion : 0.6
                    }
                )
            ).pipe(
                ClosureCompiler(
                    {
                        compilation_level : 'WHITESPACE_ONLY',
                        warning_level     : 'QUIET',
                        formatting        : formatting,
                        js_output_file    : target + '.js',
                        output_wrapper    : '\/* ' + copyright + ' *\/\n' + '%output%'
                    }
                )
            ).pipe(
                es2ToES3.gulp(
                    {
                        minIEVersion : 5
                    }
                )
            ).pipe(
                dest( tempDir )
            );
    };
};

function buildHTML( target ){
    return function( cb ){
        fs.readFile( tempDir + '/' + target + '.js',
            function( error, buffer ){
                if( error ){
                    throw error;
                };
                var js = buffer.toString();

                fs.readFile( './src/html/' + target + '.html',
                    function( error, buffer ){
                        if( error ){
                            throw error;
                        };
                        var htmlString = buffer.toString(),
                            jsdom      = new JSDOM( htmlString ),
                            document   = jsdom.window.document,
                            script     = document.getElementsByTagName( 'script' )[ 0 ];
                        
                        script.textContent = js;
                        fs.writeFile( './docs/' + target + '.html', jsdom.serialize(),
                            function( error ){
                                if( error ){
                                    throw error;
                                };
                                cb();
                            }
                        );
                    }
                );
            }
        );
    }
};

module.exports = series(
    function( cb ){
        createListFile( 'Platform', cb );
    },
    function( cb ){
        createListFile( 'Device', cb );
    },
    function( cb ){
        createListFile( 'DeviceType', cb );
    },
    function( cb ){
        createListFile( 'Engine', cb );
    },
    function( cb ){
        createListFile( 'Brand', cb );
    },
    function( cb ){
        fs.readFile( './src/js/iAm/conpare.js',
            function( err, buffer ){
                if( !err ){
                    funcConpare = '/** @suppress {checkVars} */\n' +
                                  'var ' + uaObjectName + '=' + ( minify ? '[]' : '{}' ) + ';\n' +
                                  '/** @suppress {checkVars|deprecated} */\n' +
                                  uaObjectName + '.conpare = ' +
                                  buffer.toString().split( 'iAm.conpare = ' )[ 1 ];
                    cb();
                };
            }
        )
    },
    function(){
        return src(
                [
                    './src/closure-primitives/base.js',
                    './.submodules/es2-json/.submodules/es2-core/src/js/**/*.js',
                    './src/js/**/*.js'
                ]
            ).pipe(
                ClosureCompiler(
                    {
                        dependency_mode   : 'PRUNE',
                        entry_point       : 'goog:who.all',
                        compilation_level : 'ADVANCED',
                        define            : [
                            'iAm.DEFINE.MINIFY=' + minify
                        ],
                        warning_level     : 'VERBOSE',
                        language_in       : 'ECMASCRIPT3',
                        language_out      : 'ECMASCRIPT3',
                        js_output_file    : uaObjectName + '.js',
                        output_wrapper    :
                            'goog.provide("' + uaObjectName + '");\n\n' + 
                            funcConpare +
                            '/** @suppress {checkTypes|deprecated} */\n(function(ua){\n' +
                                '%output%\n' +
                            '})(' + uaObjectName + ');'
                    }
                )
            ).pipe(
                dest( tempDir )
            );
    },
    compile( 'who' ),
    buildHTML( 'who' ),

    compile( 'index' ),
    buildHTML( 'index' )
);
