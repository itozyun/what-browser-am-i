const { series } = require( 'gulp' ),
      { compileWho, finalize, getEnumValues } = require( './common.js' ),
      fs = require( 'fs' );

let minify     = true;
let isPrettify = false;
let outputDir  = './dist';

module.exports = series(
    compileWho( false , false, minify, 'whatBrowserAmI', 'what-browser-am-i.js' ),
    finalize( true, isPrettify, outputDir, 'what-browser-am-i.js' ),
    compileWho( false, true, minify,'ua', 'index.js' ),
    finalize( false, isPrettify, outputDir, 'index.js'),

    function( cb ){
        getEnumValues(
            ( enums ) => {
                const _enums = {};

                for(const a in enums){
                    _enums[a] = {};
                    for(const b in enums[a][0]){
                        const prop = enums[a][1][b];
                        const num  = enums[a][0][b];
                        _enums[a][prop || 'Unknown'] = num;
                    };
                };

                fs.writeFile( './index.js',
`// THIS FILE GENERATED BY "gulp dist", DONT EDIT!

const enums =  ${JSON.stringify( _enums, null, '    ' )};

module.exports = (minify) => {
    function _(){
        const ret = {};

        for(const a in enums){
            ret[a] = {};
            for(const b in enums[a]){
                ret[a][b] = b;
            };
        };
    };
    return minify ? enums : _(enums);
};
`,
                    cb
                );
            }
        );
    }
);